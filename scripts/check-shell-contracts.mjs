import assert from "node:assert/strict";
import { createActionExecution, createMenuGeneration } from "../src/components/qx-shell/actionExecution.ts";
import { constrainSplitWidth, splitBounds, splitKeyWidth } from "../src/components/qx-shell/splitGeometry.ts";
import { validateQxShellActions, actionHasSubmenu } from "../src/components/qx-shell/actionProtocol.ts";

const execution = createActionExecution();
let count = 0;
let release;
const failures = [];
const action = { id: "run", label: "Run", onClick() {} };
const first = execution.run("run", action, async () => { count++; await new Promise((resolve) => { release = resolve; }); }, () => {}, (e) => failures.push(e));
assert.equal(execution.isPending("run"), true);
await execution.run("run", { ...action }, () => { count++; }, () => {}, () => {});
assert.equal(count, 1, "same action remains guarded across React object projections");
await execution.run("other", { ...action, id: "other" }, () => { count++; }, () => {}, () => {});
assert.equal(count, 2, "unrelated actions remain usable");
release(); await first;
assert.equal(execution.isPending("run"), false);
await execution.run("run", action, async () => { throw new Error("failure"); }, () => {}, (e) => failures.push(e));
assert.equal(failures.length, 1);
await execution.run("disabled", { ...action, disabled: true }, () => { throw new Error("must not run"); }, () => {}, (e) => failures.push(e));
assert.equal(failures.length, 1);
const late = execution.run("late", action, async () => { await new Promise((resolve) => { release = resolve; }); throw new Error("stale"); }, () => {}, (e) => failures.push(e));
execution.invalidate(); release(); await late;
assert.equal(failures.length, 1, "unmounted scope cannot publish an error");
const gate = createMenuGeneration();
const old = gate.next(); const current = gate.next();
assert.equal(old(), false); assert.equal(current(), true);
gate.invalidate(); assert.equal(current(), false, "close/back/route changes invalidate pending menu work");
assert.equal(actionHasSubmenu({ id: "empty", label: "Empty", children: [] }), true);
assert.deepEqual(validateQxShellActions([action]), []);
assert.ok(validateQxShellActions([{ ...action, children: [] }]).some((issue) => issue.includes("execution kind")));
const bounds = splitBounds(980, 220, 320, 420, 160);
assert.equal(constrainSplitWidth(100, bounds), 0);
assert.equal(constrainSplitWidth(999, bounds), 420);
assert.equal(splitKeyWidth("ArrowRight", 220, 24, "right", bounds), 0);
assert.equal(splitKeyWidth("ArrowLeft", 0, 24, "right", bounds), 220);
assert.equal(splitKeyWidth("Home", 300, 24, "right", bounds), 420);
assert.equal(splitKeyWidth("End", 300, 24, "right", bounds), 0);
assert.equal(splitBounds(680, 220, 320, 420).max, 352);
console.log("shell contracts: action-only, feedback generation and split geometry passed");
